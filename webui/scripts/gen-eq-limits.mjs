#!/usr/bin/env node
// Generate src/lib/eq-limits.generated.ts from the server's OpenAPI document (openapi.json):
// the band limit and the value ranges the server accepts for an EQ band. The server's
// constants in snapdog-common are the source; a Rust test keeps openapi.json in line with
// them, and a web test keeps this file in line with openapi.json.
//
//   node scripts/gen-eq-limits.mjs          write the file
//   node scripts/gen-eq-limits.mjs --check  fail if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const openapiPath = join(here, "../../openapi.json");
const outPath = join(here, "../src/lib/eq-limits.generated.ts");

function render(openapi) {
  const schemas = openapi.components.schemas;
  const band = schemas.EqBand.properties;
  const range = (field) => `{ min: ${band[field].minimum}, max: ${band[field].maximum} }`;
  return [
    "// Generated by scripts/gen-eq-limits.mjs from openapi.json. Do not edit.",
    "// Run `pnpm run eq-limits:generate` after the server's EQ limits change.",
    "",
    "/** What the server accepts for an EQ configuration. */",
    "export const SERVER_EQ_LIMITS = {",
    `  maxBands: ${schemas.EqConfig.properties.bands.maxItems},`,
    `  freqHz: ${range("freq")},`,
    `  gainDb: ${range("gain")},`,
    `  q: ${range("q")},`,
    "} as const;",
    "",
  ].join("\n");
}

const expected = render(JSON.parse(readFileSync(openapiPath, "utf8")));
if (process.argv.includes("--check")) {
  if (readFileSync(outPath, "utf8") !== expected) {
    console.error("src/lib/eq-limits.generated.ts is out of date: run `pnpm run eq-limits:generate`.");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, expected);
}
