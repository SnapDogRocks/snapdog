#!/usr/bin/env node
// Generate src/lib/ws-events.generated.ts from the server's AsyncAPI document
// (docs/api/asyncapi.json): the list of WebSocket event types the server can send.
// `src/lib/types.ts` asserts that its `WsNotification` union covers exactly these types,
// and `useAppSession` handles them in an exhaustive switch, so a new server event fails
// the type check until the interface handles it.
//
//   node scripts/gen-ws-events.mjs          write the file
//   node scripts/gen-ws-events.mjs --check  fail if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const asyncapiPath = join(here, "../../docs/api/asyncapi.json");
const outPath = join(here, "../src/lib/ws-events.generated.ts");

export function render(asyncapi) {
  const types = Object.values(asyncapi.components.messages)
    .map((m) => m.name)
    .sort();
  return [
    "// Generated by scripts/gen-ws-events.mjs from docs/api/asyncapi.json. Do not edit.",
    "// Run `pnpm run ws:generate` after the server's events change.",
    "",
    "export const WS_EVENT_TYPES = [",
    ...types.map((t) => `  "${t}",`),
    "] as const;",
    "",
    "export type WsEventType = (typeof WS_EVENT_TYPES)[number];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = render(JSON.parse(readFileSync(asyncapiPath, "utf8")));
  if (process.argv.includes("--check")) {
    const actual = readFileSync(outPath, "utf8");
    if (actual !== expected) {
      console.error("src/lib/ws-events.generated.ts is out of date: run `pnpm run ws:generate`.");
      process.exit(1);
    }
  } else {
    writeFileSync(outPath, expected);
  }
}
